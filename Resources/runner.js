// Postwoman: runs newman as a library and streams every stage as "@@PW {json}" lines on stdout.
// Usage: node runner.js <newman-package-dir> <collection.json> <globals.json> <data.json|-> <delayMs> <timeoutMs> [stdin|-]
// With `stdin`, one JSON object {name: value} with the secret variables is read from stdin (never written to a file).
'use strict';
const fs = require('fs'), path = require('path'), dns = require('dns').promises, util = require('util');
const [newmanDir, colPath, gPath, dataPath, delayMs, timeoutMs, secretsFrom] = process.argv.slice(2);
const T0 = Date.now();
const emit = o => process.stdout.write('@@PW ' + JSON.stringify(o) + '\n');
const log = (l, c, m) => emit({ e: 'log', l, c, m });
process.on('uncaughtException', err => { log('error', 'node', 'Uncaught exception: ' + (err && err.stack || err)); process.exitCode = 1; });
process.on('unhandledRejection', err => log('error', 'node', 'Unhandled rejection: ' + (err && err.stack || err)));

const hdrs = h => { try { return (h.all ? h.all() : h.members).filter(x => !x.disabled).map(x => ({ k: String(x.key), v: String(x.value) })); } catch (e) { return []; } };
// Request headers as sent. The runtime adds Content-Type for urlencoded / form-data bodies only at the socket level, so complete the list here.
const reqHdrs = rq => {
  const h = hdrs(rq.headers);
  try {
    const m = rq.body && rq.body.mode;
    if (!h.some(x => x.k.toLowerCase() === 'content-type')) {
      if (m === 'urlencoded') h.unshift({ k: 'Content-Type', v: 'application/x-www-form-urlencoded' });
      else if (m === 'formdata') h.unshift({ k: 'Content-Type', v: 'multipart/form-data; boundary=<generated by the runtime>' });
    }
  } catch (e) {}
  return h;
};
const bodyOf = b => {
  try {
    if (!b) return '';
    if (b.mode === 'raw') return b.raw || '';
    if (b.mode === 'urlencoded') return b.urlencoded.all().filter(x => !x.disabled).map(x => encodeURIComponent(x.key) + '=' + encodeURIComponent(x.value)).join('&');
    if (b.mode === 'formdata') return b.formdata.all().filter(x => !x.disabled).map(x => x.type === 'file' ? x.key + ': <file ' + (x.src || '') + '>' : x.key + ': ' + x.value).join('\n');
    if (b.mode === 'file') return '<binary file ' + ((b.file && b.file.src) || '') + '>';
    return JSON.stringify(b.toJSON());
  } catch (e) { return ''; }
};
const cap = s => (s.length > 1000000 ? s.slice(0, 1000000) + '\n…[truncated]' : s);
const kb = n => n < 1024 ? n + ' B' : (n / 1024).toFixed(1) + ' KB';


// Variables written by scripts (pm.globals / pm.environment / pm.collectionVariables .set / .unset): compared with the values the run started with and
// handed to the app, which stores them in Globals. Secret values are never written to the log.
function reportVarsImpl(summary, initial, secretNames, str) {
  const final = new Map();
  try { ((summary.globals && summary.globals.values && summary.globals.values.members) || []).forEach(m => { if (!m.disabled) final.set(String(m.key), str(m.value)); }); }
  catch (e) { log('warn', 'vars', 'cannot read the variables after the run: ' + e.message); return; }
  const set = [], unset = [];
  final.forEach((v, k) => { if (!initial.has(k)) set.push({ k, v, s: secretNames.has(k), n: 1 }); else if (initial.get(k) !== v) set.push({ k, v, s: secretNames.has(k) }); });
  initial.forEach((v, k) => { if (!final.has(k)) unset.push(k); });
  if (!set.length && !unset.length) { log('debug', 'vars', 'Scripts did not change any variable'); return; }
  const show = v => { const t = v.length > 200 ? v.slice(0, 200) + '…(' + v.length + ' chars)' : v; return JSON.stringify(t); };
  set.forEach(x => log('info', 'vars', x.s ? `Globals: ${x.n ? 'created' : 'updated'} "${x.k}" = ••• (secret, value hidden) — saved encrypted` : `Globals: ${x.n ? 'created' : 'updated'} "${x.k}" = ${show(x.v)}`));
  unset.forEach(k => log('info', 'vars', `Globals: removed "${k}"`));
  emit({ e: 'vars', set, unset });
}

(function main() {
  let newman;
  try {
    const dir = path.resolve(newmanDir);
    if (!fs.existsSync(path.join(dir, 'package.json'))) throw new Error('newman package.json not found in ' + dir);
    const ver = require(path.join(dir, 'package.json')).version;
    newman = require(dir);
    log('info', 'stage', `node ${process.version}; newman ${ver} (${dir}) loaded in ${Date.now() - T0} ms`);
  } catch (err) { log('error', 'stage', 'Cannot load newman as a library: ' + err.message); process.exitCode = 2; return; }

  const opts = { collection: JSON.parse(fs.readFileSync(colPath, 'utf8')), globals: JSON.parse(fs.readFileSync(gPath, 'utf8')), iterationCount: 1 };
  let secretKeys = [];
  if (secretsFrom === 'stdin') {
    try {
      const raw = fs.readFileSync(0, 'utf8').trim();
      const sec = raw ? JSON.parse(raw) : {};
      const names = Object.keys(sec); secretKeys = names;
      opts.globals.values = (opts.globals.values || []).filter(v => !names.includes(v.key))
        .concat(names.map(k => ({ key: k, value: String(sec[k]), enabled: true, type: 'secret' })));
      log('debug', 'vault', `${names.length} secret variable(s) received through stdin`);
    } catch (er) { log('error', 'vault', 'cannot read secret variables from stdin: ' + er.message); }
  }
  // All variables of the app live in Globals. Scripts written for Postman use pm.environment / pm.collectionVariables as well, so every script gets one
  // line in front of its first line (line numbers in error messages stay correct) that makes the three scopes the same object.
  const PRELUDE = "try{var __g=pm.globals;['get','set','unset','has','clear','toObject','replaceIn'].forEach(function(m){if(typeof __g[m]==='function'){var f=function(){return __g[m].apply(__g,arguments)};pm.environment[m]=f;pm.collectionVariables[m]=f}})}catch(e){};";
  // "Authorization: Basic user:{{password}}" (readable credentials, shown in the Headers tab) is encoded once the variables are known.
  const BASIC = "try{var __a=pm.request.headers.get('Authorization');if(__a&&/^Basic\\s+[^\\s]*:/.test(__a)){var __c=pm.variables.replaceIn(__a.replace(/^Basic\\s+/,''));pm.request.headers.upsert({key:'Authorization',value:'Basic '+CryptoJS.enc.Base64.stringify(CryptoJS.enc.Utf8.parse(__c))})}}catch(e){};";
  const inject = n => {
    if (n.request) {
      n.event = n.event || [];
      let pre = n.event.find(ev => ev && ev.listen === 'prerequest' && ev.script);
      if (!pre) { pre = { listen: 'prerequest', script: { type: 'text/javascript', exec: [''] } }; n.event.push(pre); }
      let ex = pre.script.exec; if (typeof ex === 'string') ex = ex.split('\n');
      ex = Array.isArray(ex) && ex.length ? ex.slice() : ['']; ex[0] = BASIC + ex[0]; pre.script.exec = ex;
    }
    (n.event || []).forEach(ev => {
      const sc = ev && ev.script; if (!sc) return;
      let ex = sc.exec; if (typeof ex === 'string') ex = ex.split('\n');
      ex = Array.isArray(ex) ? ex.slice() : []; if (!ex.length) ex = [''];
      ex[0] = PRELUDE + ex[0]; sc.exec = ex;
    });
    (n.item || []).forEach(inject);
  };
  try { inject(opts.collection); } catch (er) { log('warn', 'script', 'could not prepare scripts: ' + er.message); }
  const secretNames = new Set(secretKeys);
  const str = v => typeof v === 'string' ? v : (v === undefined || v === null) ? '' : typeof v === 'object' ? JSON.stringify(v) : String(v);
  const initial = new Map((opts.globals.values || []).filter(v => v.enabled !== false).map(v => [v.key, str(v.value)]));
  if (+delayMs > 0) opts.delayRequest = +delayMs;
  if (+timeoutMs > 0) opts.timeoutRequest = +timeoutMs;
  if (dataPath !== '-') opts.iterationData = dataPath;
  log('debug', 'stage', `options: delayRequest=${opts.delayRequest || 0} ms, timeoutRequest=${opts.timeoutRequest || 'none'}, data=${dataPath !== '-'}`);

  // Visualizer (pm.visualizer.set): newman drops it from the `item` event, but the `script` event still carries it.
  let Handlebars = null;
  try { Handlebars = require(require.resolve('handlebars', { paths: [path.resolve(newmanDir)] })); }
  catch (er) { log('warn', 'script', 'handlebars is not available — pm.visualizer templates will not be rendered: ' + er.message); }
  const vis = new Map();                       // item id → { template, data, options } (the latest script wins, tests after pre-request)

  let hb = null, reqT = 0, itemT = 0, curReq = null;
  const stopHb = () => { if (hb) { clearInterval(hb); hb = null; } };
  const reportVars = summary => { if (summary) reportVarsImpl(summary, initial, secretNames, str); else log('warn', 'vars', 'run failed before the end: variable changes were not saved'); };
  const run = newman.run(opts, (err, summary) => {
    stopHb();
    let st = '';
    try { const s = summary.run.stats; st = `requests ${s.requests.total} (failed ${s.requests.failed}), assertions ${s.assertions.total} (failed ${s.assertions.failed}), scripts errors ${s.prerequestScripts.failed + s.testScripts.failed}`; } catch (e) {}
    reportVars(summary);
    if (err) log('error', 'stage', 'Run error: ' + (err.message || err)); else log('info', 'stage', 'Run complete: ' + st);
    process.exitCode = err ? 1 : 0;
  });

  run.on('start', () => log('debug', 'stage', `collection run started (${Date.now() - T0} ms since node start)`));
  run.on('beforeItem', (e, a) => { itemT = Date.now(); log('info', 'stage', `▶ ${a.item.name}`); emit({ e: 'item', name: a.item.name }); });
  run.on('beforePrerequest', () => log('debug', 'stage', 'running pre-request scripts (collection → folders → request)'));
  run.on('prerequest', (e, a) => {
    if (e) log('error', 'script', 'pre-request failed: ' + (e.message || e));
    (a.executions || []).forEach(x => { if (x.result && x.result.error) log('error', 'script', 'pre-request error: ' + x.result.error.message); });
    log('debug', 'stage', `pre-request scripts done (${Date.now() - itemT} ms since item start)`);
  });
  run.on('beforeRequest', (e, a) => {
    const rq = a.request; reqT = Date.now(); curReq = rq;
    let url = ''; try { url = rq.url.toString(); } catch (x) {}
    const h = hdrs(rq.headers), body = bodyOf(rq.body);
    log('info', 'stage', `→ ${rq.method} ${url}`);
    log('debug', 'stage', `request prepared (variables resolved): ${h.length} header(s), body ${Buffer.byteLength(body)} B`);
    const un = new Set(); const re = /\{\{[^}]+\}\}/g;
    [url, body].concat(h.map(x => x.k + ': ' + x.v)).forEach(t => (t.match(re) || []).forEach(v => un.add(v)));
    if (un.size) log('warn', 'vars', 'Unresolved variables: ' + [...un].join(', ') + ' (not defined in Globals / data row)');
    let host = ''; try { host = rq.url.getHost(); } catch (x) {}
    if (host && !/^[\d.:]+$/.test(host) && host !== 'localhost') {
      const t = Date.now();
      dns.lookup(host, { all: true }).then(r => log('debug', 'net', `DNS ${host} → ${r.map(x => x.address).join(', ')} (${Date.now() - t} ms)`))
        .catch(er => log('error', 'net', `DNS ${host} failed after ${Date.now() - t} ms: ${er.code || er.message}`));
    }
    log('debug', 'net', `connecting and waiting for response (timeout ${opts.timeoutRequest ? opts.timeoutRequest / 1000 + ' s' : 'none'})`);
    stopHb();
    hb = setInterval(() => log('warn', 'net', `⏳ still waiting for response: ${Math.round((Date.now() - reqT) / 1000)} s`), 2000);
  });
  run.on('request', (e, a) => {
    stopHb();
    const rq = a.request || curReq, took = Date.now() - reqT;
    let url = '', method = ''; try { url = rq.url.toString(); method = rq.method; } catch (x) {}
    if (!a.item || !a.item.name) {                 // pm.sendRequest(...) made by a script: not a collection item, only logged
      if (e) log('error', 'sendRequest', `pm.sendRequest ${method} ${url} failed after ${took} ms: ${(e.code ? e.code + ': ' : '') + (e.message || e)}`);
      else { const r = a.response; log(r.code >= 400 ? 'warn' : 'info', 'sendRequest', `pm.sendRequest ${method} ${url} → ${r.code} ${r.status} in ${r.responseTime != null ? r.responseTime : took} ms`); }
      return;
    }
    const rec = { e: 'exec', id: a.item.id, ts: reqT, name: a.item.name, method, url, reqH: reqHdrs(rq), reqB: bodyOf(rq.body), code: 0, status: '', time: took, resH: [], resB: '' };
    if (e) {
      rec.error = (e.code ? e.code + ': ' : '') + (e.message || String(e));
      log('error', 'net', `request failed after ${took} ms: ${rec.error}`);
    } else {
      const r = a.response; let text = ''; try { text = r.text(); } catch (x) {}
      rec.code = r.code; rec.status = r.status; rec.time = r.responseTime != null ? r.responseTime : took; rec.resH = hdrs(r.headers); rec.resB = cap(text);
      let size = 0; try { size = r.size().total || r.stream.length; } catch (x) {}
      log(r.code >= 400 ? 'warn' : 'info', 'stage', `← ${r.code} ${r.status} in ${rec.time} ms, ${kb(size || Buffer.byteLength(text))}`);
      if (r.timings) log('debug', 'net', 'timings: ' + JSON.stringify(r.timings));
    }
    emit(rec);
  });
  run.on('beforeTest', () => log('debug', 'stage', 'running test scripts'));
  run.on('test', (e, a) => { if (e) log('error', 'script', 'test script failed: ' + (e.message || e)); (a.executions || []).forEach(x => { if (x.result && x.result.error) log('error', 'script', 'test error: ' + x.result.error.message); }); });
  run.on('assertion', (e, a) => emit({ e: 'assert', id: a.item.id, name: a.assertion, ok: !a.error, msg: a.error ? a.error.message : '' }));
  run.on('script', (e, a) => {
    if (e) log('error', 'script', `${a && a.event ? a.event.listen : 'script'} script failed: ` + (e.message || e));
    const v = a && a.execution && a.execution.return && a.execution.return.visualizer;
    if (v && a.item) { vis.set(a.item.id, v); log('info', 'script', `pm.visualizer.set called (${a.event ? a.event.listen : 'script'})`); }
  });
  run.on('console', (e, a) => log(a.level === 'error' ? 'error' : a.level === 'warn' ? 'warn' : 'info', 'console', `console.${a.level}: ` + util.format(...a.messages)));
  run.on('exception', (e, a) => log('error', 'script', 'script exception: ' + ((a.error && a.error.message) || a.error)));
  run.on('item', (e, a) => {
    stopHb(); log('debug', 'stage', `item "${a.item.name}" finished in ${Date.now() - itemT} ms (scripts + request)`);
    const v = vis.get(a.item.id);
    if (v) {
      vis.delete(a.item.id);
      let html = '', error = '';
      try {
        if (!Handlebars) throw new Error('handlebars is not available');
        html = Handlebars.compile(String(v.template), v.options || {})(v.data);
      } catch (er) { error = er.message || String(er); log('error', 'script', 'visualizer template error: ' + error); }
      let data = 'null'; try { data = JSON.stringify(v.data === undefined ? null : v.data); } catch (er) {}
      if (html.length > 2000000) { html = html.slice(0, 2000000); error = 'template output truncated at 2 MB'; }
      if (data.length > 2000000) data = 'null';
      emit({ e: 'visual', id: a.item.id, html, data, error });
      log('info', 'script', `visualizer rendered: ${html.length} characters${error ? ' (' + error + ')' : ''}`);
    }
    emit({ e: 'itemDone', id: a.item.id });
  });
  run.on('done', () => log('debug', 'stage', `done event, total ${Date.now() - T0} ms`));
})();
